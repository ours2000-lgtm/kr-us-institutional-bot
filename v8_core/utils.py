import os
import time
from datetime import datetime


# ---------------------------------------------------------------------
# 안전 로그 (모든 엔진에서 사용)
# ---------------------------------------------------------------------
def safe_log(msg, log_path=None):
    ts = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    line = f"[{ts}] {msg}"

    print(line)

    if not log_path:
        return

    try:
        os.makedirs(os.path.dirname(log_path), exist_ok=True)
        with open(log_path, "a", encoding="utf-8") as f:
            f.write(line + "\n")
    except:
        pass


# ---------------------------------------------------------------------
# 현재 시간 문자열
# ---------------------------------------------------------------------
def now_time():
    return datetime.now().strftime("%H:%M:%S")


# ---------------------------------------------------------------------
# 현재 날짜 문자열
# ---------------------------------------------------------------------
def today_str():
    return datetime.now().strftime("%Y-%m-%d")


# ---------------------------------------------------------------------
# sleep 안전 버전
# ---------------------------------------------------------------------
def safe_sleep(sec):
    try:
        time.sleep(sec)
    except:
        pass
