# =====================================================================
# run_all_v9_plus.py — 글로벌 자동매매 V9 PLUS 통합 실행 엔진
# =====================================================================
# 역할:
#   ✔ 한국장 run_korea_v9_plus.py 자동 실행
#   ✔ 미국장 run_us_v9_plus.py 자동 실행
#   ✔ 독립 프로세스 구성 (병렬 실행)
#   ✔ 오류 감지 후 자동 재시작(optional)
#   ✔ 단일 실행 파일로 전세계 시장 운영
# =====================================================================

import subprocess
import time
import os
from utils_v9 import safe_log

BASE = os.path.dirname(os.path.abspath(__file__))

KR_PATH = os.path.join(BASE, "run_korea_v9_plus.py")
US_PATH = os.path.join(BASE, "run_us_v9_plus.py")


# =====================================================================
# 프로세스 실행 함수
# =====================================================================
def start_engine(name, path):
    safe_log(f"[RUN_ALL] {name} 엔진 시작: {path}")
    return subprocess.Popen(["python", path])


# =====================================================================
# 메인
# =====================================================================
def main():

    safe_log("====================================================")
    safe_log("     🌏 Global Auto-Trading V9 PLUS — Master Engine")
    safe_log("====================================================")

    # ----------------------------
    # 한국장 엔진 실행
    # ----------------------------
    kr_proc = start_engine("한국장", KR_PATH)
    safe_log("[RUN_ALL] 한국장 엔진 가동 완료")

    # ----------------------------
    # 미국장 실행까지 대기
    # ----------------------------
    safe_log("[RUN_ALL] 미국장 오픈 시간까지 대기 중…")

    while True:
        now = time.strftime("%H:%M:%S")

        # 미국장 시작 시간 체크 (config를 직접 읽어도 되지만 간단히 하드코딩)
        if now >= "23:20:00":
            break

        time.sleep(10)

    # ----------------------------
    # 미국장 엔진 실행
    # ----------------------------
    us_proc = start_engine("미국장", US_PATH)
    safe_log("[RUN_ALL] 미국장 엔진 가동 완료")

    # ----------------------------
    # 두 시장 모두 모니터링
    # ----------------------------
    while True:
        time.sleep(5)

        # 한국장 엔진 종료되면 자동 재시작 (안전 모드)
        if kr_proc.poll() is not None:
            safe_log("[RUN_ALL] 한국장 엔진 다운 → 자동 재시작")
            kr_proc = start_engine("한국장", KR_PATH)

        # 미국장 엔진 종료되면 자동 재시작 (안전 모드)
        if us_proc.poll() is not None:
            safe_log("[RUN_ALL] 미국장 엔진 다운 → 자동 재시작")
            us_proc = start_engine("미국장", US_PATH)


# =====================================================================
# 실행
# =====================================================================
if __name__ == "__main__":
    main()
